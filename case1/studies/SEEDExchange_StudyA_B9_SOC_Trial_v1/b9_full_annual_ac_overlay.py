#!/usr/bin/env python3
"""Source-verified 2025 full-year B9 AC overlay and loss comparison.

Prerequisites: (1) completed B9 stress-PASS trial, (2) nine-factor changed-hour
PASS screen, (3) 18 signed full-year ORIGINAL B9 AC factor replays generated by
validate_frontier_ac.py. NO new PyPSA optimization and NO new 8,760-hour AC
simulation: re-solve only the 6 changed case-hours for each of 9 factors, then
reuse 2025 ORIGINAL AC rows for every unchanged hour at the SAME factor.

Each factor is balanced, provisional A1 transformer 106039, assumed 5 kVA.
Output is a new summary plus the 108 reproducible changed-hour AC records.
"""
from __future__ import annotations
import argparse
import importlib.util
import json
from pathlib import Path

import numpy as np
import pandas as pd

FACTOR_VALUES = tuple((pf, lf) for pf in (.95, .98, 1.0) for lf in (1.0, 1.3, 1.6))
REQUIRED = {'min_v_pu','max_v_pu','max_trafo_pct','max_line_pct','loss_kw','pcc_kva'}


def load_neighbour(name, filename):
    path = Path(__file__).with_name(filename)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise FileNotFoundError(path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def verified_original_case(repo, source_root, b9, frontier, ctx, case_data, case, pf, length):
    """Verify the EXACT same-source annual original AC replay for this factor."""
    frame = case_data['frame']
    cid = f'{case}_pf{round(pf*100):03d}_l{round(length*10):02d}'
    directory = source_root / cid
    signed = {
        'case_id':case, 'scenario':'A1', 'transformer':'106039',
        'pf':pf, 'length_factor':length, '2025_hours':8760,
        'new_energy_manifest_sha256':case_data['energy_manifest_sha'],
        'source_v6_2_sha256':frontier.sha(repo / ctx['st'].RUNNER_REL),
        'input_manifest_sha256':frontier.sha(ctx['mp']),
        'q_ratio_daylight':.25, 'night_q_disabled':True,
        'method':'independent_hourly_balanced_pandapower_replay'
    }
    summary = frontier.check_saved(directory,signed)
    if summary is None:
        raise FileNotFoundError(f'Signed original 8760h AC replay missing: {directory}')
    with open(frontier.xp(directory / 'ac_hourly.csv'),encoding='utf-8',newline='') as stream:
        old = pd.read_csv(stream,parse_dates=['timestamp_lst']).set_index('timestamp_lst')
    if not old.index.equals(frame.index) or len(old)!=8760 or old.index.has_duplicates:
        raise ValueError(f'Original AC chronology incompatible: {cid}')
    if not np.allclose(old.inverter_ac_kw.to_numpy(float),frame.inverter_ac_kw.to_numpy(float),atol=5e-6,rtol=0):
        raise ValueError(f'Original AC inverter not source-consistent: {cid}')
    if not np.allclose(old.gross_demand_kw.to_numpy(float),ctx['trace'].sum(axis=1).to_numpy(float),atol=5e-6,rtol=0):
        raise ValueError(f'Original AC 11-house demand changed: {cid}')
    if not b9.validated_ac_mask(frontier,old).equals(old.ac_feasible.astype(bool)):
        raise ValueError('Source AC flags changed')
    return old,summary


def signed_screen_gate(repo, stress, screening, b9, nine, prepared):
    """Require successful stress and nine-factor sources with exact case-hour coverage."""
    stress_manifest,saved_stress = nine.check_result_gate(repo,stress,prepared,b9)
    path = screening / 'SCREEN_MANIFEST.json'
    if not path.is_file():
        raise FileNotFoundError('Signed nine-factor changed-hour manifest missing')
    manifest = json.loads(path.read_text(encoding='utf-8'))
    if manifest.get('status')!='NINE_FACTOR_CHANGED_HOURS_PASS_ONLY' or manifest.get('AC_calls')!=108:
        raise ValueError('Nine-factor changed-hour screen has not passed')
    if manifest.get('may_claim_full_year_feasibility') is not False or manifest.get('annual_pf_length_checks_completed')!=0:
        raise ValueError('Mislabelled annual coverage in changed-hour screen')
    expected_sha={k:prepared[k]['energy_manifest_sha'] for k in b9.CASES}
    if manifest.get('source_energy_manifest_sha256')!=expected_sha:
        raise ValueError('Changed-hour source energy manifests differ')
    if manifest.get('source_stress_sha256')!=b9.sha(stress/'TRIAL_MANIFEST.json'):
        raise ValueError('Nine-factor screen is not derived from this stress trial')
    source = screening/'ALL_NINE_CHANGED_HOUR_AC.csv'
    df = pd.read_csv(source,parse_dates=['timestamp_lst'])
    needed={'case_id','pf','length_factor','phase','timestamp_lst',
            'min_v_pu','max_v_pu','max_trafo_pct','max_line_pct','status','ac_feasible'}
    if not needed.issubset(df) or len(df)!=108:
        raise ValueError('Changed-hour table incomplete')
    identity=['case_id','pf','length_factor','phase','timestamp_lst']
    if df.duplicated(identity).any():
        raise ValueError('Duplicate nine-factor changed-hour identity')
    expected={(case,pf,lf,phase,t)
       for case in b9.CASES for pf,lf in FACTOR_VALUES
       for phase in ('original','candidate')
       for t in nine.changed_timestamps(prepared[case])}
    actual={(r.case_id,float(r.pf),float(r.length_factor),r.phase,r.timestamp_lst)
            for r in df.itertuples()}
    if actual!=expected:
        raise ValueError('Nine-factor table does not cover exactly the six changed case-hours')
    if not (df.status=='CONVERGED').all() or not df[df.phase=='candidate'].ac_feasible.astype(bool).all():
        raise ValueError('Saved nine-factor changed-hour case is not fully feasible')
    if len(manifest.get('factor_case_summaries',[]))!=18:
        raise ValueError('Incorrect nine-factor source coverage')
    return df,manifest,stress_manifest


def compare_ac(record, prior, label, case, pf, lf, t):
    """Require original AC reproducibility or exact nine-factor new AC agreement."""
    if str(record.get('status'))!='CONVERGED':
        raise RuntimeError(f'Changed-hour AC failed: {case}/{pf}/{lf}/{t}/{label}')
    for col in REQUIRED:
        val=float(record[col])
        if not np.isfinite(val):
            raise ValueError(f'Non-finite changed-hour AC metric: {col}')
    for col in ('min_v_pu','max_v_pu','max_trafo_pct','max_line_pct'):
        if abs(float(record[col])-float(prior[col]))>2e-4:
            raise ValueError(f'Signed {label} AC mismatches replay {case}/{pf}/{lf}/{t}/{col}')
    if bool(record.get('ac_feasible'))!=bool(prior['ac_feasible']):
        raise ValueError('Changed-hour original/candidate AC flag mismatch')


def summarize(old,new,case,pf,lf,source_meta,frontier,b9,changed):
    base=b9.validated_ac_mask(frontier,old)
    corrected=b9.validated_ac_mask(frontier,new)
    if not np.isfinite(old.loss_kw.to_numpy(float)).all() or not np.isfinite(new.loss_kw.to_numpy(float)).all():
        raise ValueError('Non-finite loss values in full-year AC source or overlay')
    return {
      'case_id':case,'pf':pf,'length_factor':lf,
      'year_hours':len(new),'changed_hours_revalidated':len(changed),
      'baseline_bad_hours':int((~base).sum()),
      'corrected_bad_hours':int((~corrected).sum()),
      'corrected_min_voltage_pu':float(new.min_v_pu.min()),
      'corrected_max_voltage_pu':float(new.max_v_pu.max()),
      'corrected_max_trafo_pct':float(new.max_trafo_pct.max()),
      'corrected_max_line_pct':float(new.max_line_pct.max()),
      'baseline_ac_losses_kwh':float(old.loss_kw.sum()),
      'corrected_ac_losses_kwh':float(new.loss_kw.sum()),
      'delta_ac_losses_kwh':float(new.loss_kw.sum()-old.loss_kw.sum()),
      'source_original_ac_sha256':source_meta['ac_hourly_sha256'],
      'coverage':'SIGNED_8760H_ORIGINAL_PLUS_INDEPENDENT_CHANGED_HOUR_AC_REPLAY',
    }


def execute(repo, source_root, stress, screening, out, preflight=False):
    repo=repo.resolve()
    if not preflight and out.exists():
        raise FileExistsError(f'Protected output folder already exists: {out}')
    b9=load_neighbour('b9_original_signed_trial','b9_soc_trial.py')
    nine=load_neighbour('b9_9f_source_screen','b9_nine_factor_changed_hours.py')
    frontier,ctx,prepared=b9.prepare(repo,.60,.80)
    # The source runner path is authoritative, declared by the signed study module.
    path=repo/'case1/studies/SEEDExchange_StudyA_PVBESS_v1'
    import sys
    if str(path) not in sys.path:sys.path.insert(0,str(path))
    import study_a_pvbess as st
    ctx['st']=st
    screening_df,screen_meta,stress_meta=signed_screen_gate(repo,stress,screening,b9,nine,prepared)
    originals={}
    for case in b9.CASES:
        for pf,lf in FACTOR_VALUES:
            originals[(case,pf,lf)]=verified_original_case(
                repo,source_root,b9,frontier,ctx,prepared[case],case,pf,lf)
    if preflight:
        return {'status':'ALL_SOURCES_PREFLIGHT_PASS_NO_AC_SOLVER',
                'signed_original_full_year_cases':len(originals),
                'screen_changed_hour_AC_calls':screen_meta['AC_calls'],
                'originals_reused_stress':2,'unverified_PV_or_battery_hardware':True}
    ctx['v6'].repo_modules(repo)
    from run_epm_validation import build_net
    import pandapower as pp
    checks,summary=[],[]
    for case in b9.CASES:
        trial=prepared[case]
        changed=nine.changed_timestamps(trial)
        for pf,lf in FACTOR_VALUES:
            source,source_meta=originals[(case,pf,lf)]
            candidate=source.copy(deep=True)
            territory=ctx['v6'].new_territory(repo,'A1','106039',ctx['houses'],lf)
            net,nodes=build_net(territory,'head')
            if set(nodes['loads'])!=set(ctx['houses']):
                raise ValueError('Mapped network household membership changed')
            for t in changed:
                for label,frame in (('original',trial['frame']),('candidate',trial['candidate'])):
                    record=ctx['v6'].solve_ac_hour(
                        net,nodes,territory,t,ctx['trace'].loc[t],pf,
                        float(frame.loc[t,'inverter_ac_kw']),
                        float(trial['hardware']['inverter_kva']),
                        float(frame.loc[t,'pv_dc_available_kw']),.25,9,'pvbess',pp)
                    matched=screening_df[
                        (screening_df.case_id==case) &
                        (abs(screening_df.pf-pf)<1e-9) &
                        (abs(screening_df.length_factor-lf)<1e-9) &
                        (screening_df.phase==label) &
                        (screening_df.timestamp_lst==t)]
                    if len(matched)!=1:raise ValueError('Signed changed-hour reference row missing')
                    compare_ac(record,matched.iloc[0],label,case,pf,lf,t)
                    if label=='original':
                        baseline=source.loc[t]
                        for key in REQUIRED:
                            if abs(float(baseline[key])-float(record[key]))>2e-4:
                                raise ValueError(f'Full original AC source mismatch: {case}/{pf}/{lf}/{t}/{key}')
                    else:
                        b9.overlay_ac_hour(candidate,t,record)
                    checks.append({'case_id':case,'pf':pf,'length_factor':lf,
                        'timestamp_lst':str(t),'phase':label,
                        'inverter_ac_kw':float(frame.loc[t,'inverter_ac_kw']),
                        **{k:record[k] for k in ('status','ac_feasible','min_v_pu','max_v_pu',
                           'max_trafo_pct','max_line_pct','loss_kw','pcc_kva')}})
            summary.append(summarize(source,candidate,case,pf,lf,source_meta,frontier,b9,changed))
            print(f'Annual overlay {case} PF {pf} length {lf}: corrected failing hours = {summary[-1]["corrected_bad_hours"]}',
                  flush=True)
    if len(summary)!=18 or len(checks)!=108:
        raise ValueError('Annual source overlay coverage incomplete')
    pass_all=all(row['corrected_bad_hours']==0 for row in summary)
    manifest={
       'status':'FULL_ANNUAL_ALL_NINE_MODELLED_AC_PASS' if pass_all else 'FULL_ANNUAL_AC_REMAINING_FAILURES',
       'base_mode':'Original 2025 full-year AC per SAME factor, overlay with changed-hour original-solver replay',
       'source_screen_manifest_sha256':b9.sha(screening/'SCREEN_MANIFEST.json'),
       'source_stress_manifest_sha256':b9.sha(stress/'TRIAL_MANIFEST.json'),
       'factors':FACTOR_VALUES,'households':ctx['houses'],
       'source_annual_ac_root':str(source_root),
       'net_type':'Provisional balanced A1 EPM 106039, 5 kVA assumed only',
       'original_hourly_ac_screens_verified':18,
       'changed_hour_AC_replays_this_run':len(checks),
       'new_full_year_AC_solves_this_run':0,
       'year':2025,'year_hours':8760,'results':summary,
       'note':'Not a field protection/islanding certification or real network CAPEX; no new economic re-optimization'
    }
    serialized=json.dumps(manifest,indent=2,allow_nan=False,default=float)+'\n'
    out.mkdir(parents=True,exist_ok=False)
    pd.DataFrame(checks).to_csv(out/'CHANGED_HOUR_REPLAY_WITH_LOSSES.csv',index=False,float_format='%.10f')
    pd.DataFrame(summary).to_csv(out/'ANNUAL_NINE_FACTOR_B9_RESULTS.csv',index=False,float_format='%.10f')
    (out/'ANNUAL_AC_MANIFEST.json').write_text(serialized,encoding='utf-8')
    return {'status':manifest['status'],'full_year_factor_cases':18,
            'AC_replays':len(checks),'out':str(out),
            'annual_sources_solved_before_this_step':18}


def main(argv=None):
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--repo-root',type=Path,default=Path('.'))
    ap.add_argument('--source-root',type=Path,default=Path('StudyA_A1_106039_Frontier_AC_v1'))
    ap.add_argument('--stress-root',type=Path,default=Path('StudyA_A1_106039_B9_SOC_Trial_v2'))
    ap.add_argument('--screen-root',type=Path,default=Path('StudyA_A1_106039_B9_NineFactor_ChangedHour_v1'))
    ap.add_argument('--out',type=Path,default=Path('StudyA_A1_106039_B9_FullAnnual_AC_Overlay_v1'))
    ap.add_argument('--preflight',action='store_true')
    args=ap.parse_args(argv)
    print(json.dumps(execute(args.repo_root,args.source_root,args.stress_root,args.screen_root,
                             args.out,args.preflight),indent=2))


if __name__=='__main__':
    main()
